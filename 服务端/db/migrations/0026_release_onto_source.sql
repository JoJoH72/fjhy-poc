ALTER TABLE release_asset DROP CONSTRAINT IF EXISTS ck_asset_layer;

ALTER TABLE release_asset ADD CONSTRAINT ck_asset_layer CHECK (layer IN
    ('文件', '规则', '规则参数', '本体源文件',
     '业务本体', '规则本体', '流程本体',
     '事实模型', '规则绑定'));

COMMENT ON CONSTRAINT ck_asset_layer ON release_asset IS
  '九层。**层名是对外契约**：/api/pub/v1/releases/{版本}/layers/{层名} 直接用它，'
  '资产包里的文件名也按它命名。改层名等于改别人的集成代码，'
  '所以要改先加新层、两版并存，不要原地重命名。';
