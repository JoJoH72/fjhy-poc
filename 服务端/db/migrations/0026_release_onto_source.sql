-- 0025 冻了八层，三元本体那三层取的是**库里的投影**（ontology_* / process_*）。
-- 投影够用于程序消费，但少了两样东西，而这两样恰恰是本体资产最贵的部分：
--
--   ① **注释**。本体_v0.1.yaml 的 925 行里有大量口径说明与踩坑记录，
--      投影进库只剩结构，注释全丢。CLAUDE.md 第 10 条讲的就是这个：
--      注释里往往是最贵的信息，而这种损失在 review 里极难发现。
--   ② **权威性**。YAML 是源头，库是投影（单向，永不回写）。
--      消费方要能自己验「这一版的本体到底长什么样」，就得拿到源文件本身。
--
-- 所以源文件原文单独冻成一层，而不是塞进三元本体里的某一层——
-- 塞进去的话，下一个人要回答「源文件为什么在规则本体下面」，答不出来。
--
-- 用户 2026-10-19 的原话里「允许被其他业务消费。例如 API、本体等」，
-- 本体作为被消费对象，给的就该是这一份。
