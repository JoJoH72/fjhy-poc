-- ============================================================================
-- 0022 · 规则本体：对账结论补「编号对不上」一档
-- ----------------------------------------------------------------------------
-- 0021 给 onto_rule_cover.state 定了四档，少了一档，而少的这一档恰好是
-- **实测里数量最多的那种真实情况**。
--
-- 实测（2026-10-19，82 条规则 × 185 条条款）：
--   有制度依据 31 · 来源未写明 41 · 剩下 10 条按 0021 的四档只能落「查无依据」。
-- 但把那 10 条逐条摊开看，没有一条是真的查无依据：
--   TR-D3-06  要点 2.3.1 表第1行    ← 指向条款**内的表格行**，我们切到 2.3.1 整条
--   TR-D4-08  解答 解答3            ← 问答序号，不是条款号
--   TR-D4-16  制度 附件4 解答2       ← 附件内的解答
--   TR-D6-06  制度 第二十三条（三）    ← **款**级，我们切到条级
--   TR-D9-01  要点 多处（2.1.2/2.1.3/…）← 一个来源写了多处，压根不是单值
--
-- **把这 10 条标成「查无依据」是误报，而且是最贵的那种误报**：它宣称
-- 10 条规则没有制度依据，看报告的人会去改规则或删规则，
-- 而真正该做的是把条款切分做到款级/行级，或者在来源字段里补一层映射。
-- 漏报放过风险，误报会让人动手改对的东西——两个方向都必须测，
-- 这一档就是正向测出来的。
--
-- 四档变五档，「查无依据」这一档保留且实测为 0。**保留空档是有意的**：
-- 它在页面上就是一句「真的找不到依据的规则：0 条」，
-- 这句话和「我们没查」是两件事，而只有把档位留着才说得出口。
-- ============================================================================

ALTER TABLE onto_rule_cover DROP CONSTRAINT IF EXISTS ck_orc_state;
ALTER TABLE onto_rule_cover ADD CONSTRAINT ck_orc_state
    CHECK (state IN ('有制度依据', '仅规则表', '编号对不上', '查无依据', '来源未写明'));

COMMENT ON COLUMN onto_rule_cover.state IS
  '五档，每一档对应**不同的责任方和不同的下一步动作**，所以一档都不能并：'
  '有制度依据 —— 条款号精确命中，证据链通了；'
  '仅规则表   —— 只被规则表（xlsx）的行引用。规则表是客户人工整理的二手产物，'
  '              制度文件才是法源，这条可能是业务惯例而非制度要求；'
  '编号对不上 —— 文件钉到了，条款号在该文件的条款清单里找不到：'
  '              来源写的是款级（第二十三条（三））、表内行（2.3.1 表第1行）、'
  '              问答序号（解答3）或多处。**这不是没有依据，是两套编号对不上**，'
  '              该做的是把切分做到款级/行级，不是去改规则；'
  '查无依据   —— 文件钉到了、编号形态也一致，但那一条确实不存在。'
  '              实测 0 条。**空档保留**：「真的查无依据的：0 条」'
  '              和「我们没查」是两件事，留着档位才说得出这句话；'
  '来源未写明 —— 规则的 source_clause 写的是类别代号（规则表/要点/制度/场景表/'
  '              配置器/解答）而不是文件名，代号在文件库里对不到唯一一份文件。'
  '              实测 41 条，占一半——这是台账口径问题，不是规则质量问题。';
