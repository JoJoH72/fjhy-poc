-- ============================================================================
-- 0031 · 场景表那一路：第三种来源「场景拆条」
-- ----------------------------------------------------------------------------
-- 《财务共享业务场景核算及审核规则.xlsx》的「业务域」工作表有 1709 行，
-- 每行是一个业务场景（业务域×单据×大类×小类），其中「专用审核要点」那一列
-- 才是审核规则。实测这张表的三件事决定了它该怎么拆：
--
-- ① **它以前一条都没进来。** 切表格行要求行首是序号数字，而这 1709 行
--    行首是「费用报账域」——匹配 0 行。而**匹配上的 9 条全部来自
--    「业务域联系人」工作表**：9 个真实姓名加手机号，被当成规则条款入了库。
-- ② **要点正文高度重复。** 差旅+接待两类单据共 163 行，
--    「专用审核要点」的正文**只有 2 种**（差旅那种含 2 条要点、
--    招待那种含 3 条要点），客户是按业务小类逐行重复填的。
--    按行拆会得到 163 条几乎一样的「规则」，按正文去重再按序号拆才是 5 条。
-- ③ **人工抽过的那 9 条就是这么拆的。** rule 表里 source_clause.file='场景表'
--    的 9 条规则，clause 写的是「专用审核要点 3」「专用审核要点 7」
--    「报账附件列」——粒度是**要点的第几条**，不是表的第几行。
--    自动抽取跟人工口径对齐，两边才对得上账。
--
-- 所以 origin 多一档「场景拆条」，而不是混进「列映射」：
-- 列映射是**一行对一条规则**，场景拆条是**多行去重后再按序号拆成多条**，
-- 两者的证据链长相不同（后者要记「这条要点覆盖了多少行、哪些业务小类」）。
-- 混成一档，页面上就看不出哪条规则背后是 1 行、哪条背后是 163 行。
-- ============================================================================

ALTER TABLE doclib_rule_detail DROP CONSTRAINT IF EXISTS ck_drd_origin;
ALTER TABLE doclib_rule_detail ADD CONSTRAINT ck_drd_origin
    CHECK (origin IN ('列映射', '场景拆条', 'AI草稿'));

COMMENT ON COLUMN doclib_rule_detail.origin IS
  '列映射   = 表格行按**表头名**映射，一行一条规则。确定性、不出网、不计费。'
  '场景拆条 = 场景表的「专用审核要点」按正文去重、再按条内序号拆。'
  '          同样确定性，但一条规则背后是很多行（实测差旅那条覆盖 163 行里的大半），'
  '          所以 note 里要记清覆盖了多少行、哪些业务小类。'
  'AI草稿   = 大模型从制度条款原文抽的八要素，要过数值幻觉核对。'
  '实测对照：《差旅费审核规则.xlsx》第 5 行，列映射一次拿到 '
  '规则名称/判定逻辑/控制类型/实现途径/是否已有 五项；'
  '模型花 58 秒把前三项「猜」了一遍（值对），后两项丢了，风险等级和例外给的是 null。';

-- mapped_ok 的口径在实现过程中收紧过一次，注释要跟上：
-- 它只说**列对不对齐**（结构），不说取值对不对。
COMMENT ON COLUMN doclib_rule_detail.mapped_ok IS
  'FALSE = 这一行**列没对齐**，没有按列映射，只留了原文等人看。'
  '判据是结构：本行列数与表头不一致，且没有一种对齐方式说得通。'
  '**「取值不在闭集合」不算列错位**——实扫《差旅费审核规则.xlsx》的「实现途径」列，'
  '客户自己填的是「？」「通过OA控制？」「AI智能审核？」，列是对的、值待定；'
  '那种情况该列留空、原值进 note，mapped_ok 仍然是 TRUE。'
  '第一版把两者混成一种，实测把 7 条干干净净的规则挡在了外面。'
  '**静默丢掉是漏报，硬映射是误报，两者同样致命。**';
