-- ============================================================================
-- 0030 · 规则明细的「分类（标签）」
-- ----------------------------------------------------------------------------
-- 标签体系的全部设计决定都在这里，因为它是最容易做错的一块：
--
-- ① **闭集合标签不存在这张表里。**
--    费用维度（D1..D10）、控制类型（禁止/警告）、规则类型（硬/混合/软）、
--    来源类别、实现途径、落地状态、可信度 —— 这七个维度全部**由明细的列派生**，
--    不另存一份。
--    理由是本项目踩过的坑：文件类别曾经由「文件库」和「抽取」各判一套，
--    于是清单上出现「文件库说它是单据、抽取说它是制度」，没人知道该信哪个。
--    **同一个事实存两处，必然有一天对不上。**
--    派生的代价只是每次查询算一遍，换来的是永远一致。
--
-- ② **这张表只收人加的自由标签。**
--    闭集合表达不了但必须记的话：「待共享侧补授权记录」「比18号文第十四条宽」
--    「客户现场确认过口径」。它们没有取值范围，也不该有——
--    硬塞进闭集合就会逼着人选一个最接近的，而那个选择后面会被当成事实。
--
-- ③ **每个标签都要能回答「凭什么」。**
--    标签是用来筛选的：筛错了就抽错样本，而抽错的样本会被当成结论。
--    所以人加的标签必须有 tagged_by 和 why；派生的标签在接口里带 src
--    （哪一列给的 / 哪个模型给的）。**没有依据的标签等于没有。**
--
-- ④ **标签不许模型自由生成。**
--    实测两次调用给出的「审核维度」是「差旅费报销」和
--    「人员身份，审批手续，交通住宿补贴，报销频次」——一个都不在 D1..D10 里。
--    模型只能在闭集里选，选不出就留空由人填（doclib_rule_detail.dimension 为空），
--    不硬塞。硬塞的后果是一条维度错的规则看起来填得整整齐齐。
-- ============================================================================

CREATE TABLE IF NOT EXISTS doclib_detail_tag (
    detail_id  TEXT        NOT NULL REFERENCES doclib_rule_detail(detail_id)
                               ON DELETE CASCADE,
    tag        TEXT        NOT NULL,
    tagged_by  TEXT        NOT NULL,
    why        TEXT        NOT NULL,
    tagged_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (detail_id, tag),
    -- 空标签、空署名、空理由都不许：三者缺一，这条标签以后就没人能解释
    CONSTRAINT ck_dtag_tag CHECK (btrim(tag) <> ''),
    CONSTRAINT ck_dtag_by  CHECK (btrim(tagged_by) <> ''),
    CONSTRAINT ck_dtag_why CHECK (btrim(why) <> '')
);

COMMENT ON TABLE doclib_detail_tag IS
  '**人**加在规则明细上的自由标签。闭集合的七个维度（费用维度/控制类型/'
  '规则类型/来源类别/实现途径/落地状态/可信度）不在这里——那些由明细的列派生，'
  '存两处必然对不上（文件类别就这么错过一次）。'
  '这里只收闭集合表达不了的话，而且必须带署名和理由。';

COMMENT ON COLUMN doclib_detail_tag.why IS
  '为什么打这个标签。**标签是用来筛选的**，筛错了就抽错样本，'
  '而抽错的样本会被当成结论。所以每个标签都要能回答「凭什么」。';
