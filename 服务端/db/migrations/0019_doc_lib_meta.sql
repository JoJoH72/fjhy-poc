-- ============================================================================
-- 0019 · 只读文件库：文件级属性（分类 / 文号 / 标题 / 发文年份）
-- ----------------------------------------------------------------------------
-- 这四样都是**文件自己的属性**，所以归在文件库这一栏，不归规则抽取。
-- 边界的那条线是：**本栏只回答「库里有哪些文件、是什么、能不能识别」，
-- 不回答「里面写了什么」。** 内容（正文、条款、规则草稿）属于下一栏。
--
-- 为什么分类必须有「单据」这一档：
--   实扫客户资料 14 份，其中 5 份是报账单明细表和差旅费审批意见——
--   那是**业务单据**，不是制度。混在同一张清单里看不出来，
--   而下游「制度里还有多少条没变成规则」这个数字会把它们一起算进去，
--   数字就失真了。范本（合同、申请书、模板）同理，单独一档。
--
-- 为什么文号/标题**只从文件名取**，不从正文取：
--   项目纪律：溯源只认文件名上的硬证据。实测 OCR 把
--   「闽港财智〔2025〕20号」识别成「赣港财知2025] 20号」——
--   拿正文里的文号去匹配必然错配，而错配给出的是一条
--   「看起来有据可查、实际指错地方」的证据链，比标「未匹配」危险得多。
--   取不到就留空，**不猜**。
-- ============================================================================

ALTER TABLE doc_lib_file
    ADD COLUMN IF NOT EXISTS doc_kind    TEXT,
    ADD COLUMN IF NOT EXISTS doc_number  TEXT,
    ADD COLUMN IF NOT EXISTS doc_title   TEXT,
    ADD COLUMN IF NOT EXISTS issued_year INTEGER,
    ADD CONSTRAINT ck_doclib_file_kind CHECK
        (doc_kind IS NULL OR doc_kind IN ('制度', '范本', '单据', '其他'));

CREATE INDEX IF NOT EXISTS ix_doclib_file_kind ON doc_lib_file (doc_kind);
CREATE INDEX IF NOT EXISTS ix_doclib_file_no   ON doc_lib_file (doc_number);

COMMENT ON COLUMN doc_lib_file.doc_kind IS
  '制度 | 范本 | 单据 | 其他。按**文件名**判，判不出就是「其他」，不猜。'
  '单据=报账单、审批意见、明细表这类业务单据；范本=合同、申请书、模板这类文书模板。'
  '两者都不该参与「制度里还有多少条没变成规则」的统计——'
  '实扫 14 份客户资料里就有 5 份是单据，一起算进去数字就失真了。';

COMMENT ON COLUMN doc_lib_file.doc_number IS
  '文号，如 闽港财智〔2025〕20号。**只从文件名取，不从正文取。**'
  '实测 OCR 把「闽港财智〔2025〕20号」识别成「赣港财知2025] 20号」，'
  '拿正文里的文号去匹配必然错配——而错配给出的是一条看起来有据可查、'
  '实际指错地方的证据链，比标「未匹配」危险得多。取不到就留空。';

COMMENT ON COLUMN doc_lib_file.doc_title IS
  '书名号里的整串标题，如《差旅管理实施细则》。同样只认文件名上的硬证据。'
  '一份文件名里出现多个书名号时取最长的那个：'
  '「关于印发《业务接待管理办法》的通知（闽港财智〔2025〕18号）」里，'
  '要的是被印发的那份办法，不是「通知」本身。';
