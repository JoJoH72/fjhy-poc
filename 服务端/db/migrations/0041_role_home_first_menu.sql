-- 0041 · 落地页统一改成「左侧第一个菜单」
-- ----------------------------------------------------------------------------
-- 背景（2026-10-25，用户提出）：登录后落到的页面不是左侧第一个菜单，
-- 系统管理员落在第 3 个「系统自检」、审核岗落在第 2 个「审核工作台」。
-- 这是 0040 里按「各角色主要在哪干活」手配的 home，不是随机跳。
--
-- 但配置出来的结果有两个问题：
--   ① 左侧高亮不在第一项，用户第一眼会以为菜单跳错了或权限少了；
--   ② 这一列在页面上没有入口，改不了，看起来像系统行为而不是配置。
-- 用户选择统一成「第一个菜单」——落地页与导航顺序一致，行为可预期。
--
-- 只改有变化的两个角色；工程师（/asset/docs）与领导（/dash）本来就是第一项。
-- 自定义角色的 home 由 app/api/iam.py 的 _first_home() 在创建时按同一顺序算。
-- ============================================================================

UPDATE sys_role SET home = '/review/ai-review' WHERE role_key = 'auditor';
UPDATE sys_role SET home = '/sys/agents'       WHERE role_key = 'admin';

COMMENT ON COLUMN sys_role.home IS
  '登录后落地页。口径：默认取该角色可见菜单里「左侧第一个」；失权时前端退到第一个有权限的菜单';
