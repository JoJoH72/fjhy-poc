-- 【同时改掉 0032 里那句注释口径】
--   0032 把报表写成「占位领域：目前没有实例也没有资产」。现在它有实例了，
--   那句话留着会误导下一个看库注释的人。**没有资产**这件事仍然成立，
--   所以 note 改成说清楚这一点：有实例，但实例下还没有任何资产。
