INSERT INTO domain_instance (instance_id, domain_id, label, is_default, sort_no, note) VALUES
    ('hdjt', 'report', '华电集团', TRUE, 10,
     '报表领域的实例。**目前没有任何资产归属于它**——制度文件、规则、本体、'
     '发布版本全部属于「审核 / 福建海运集团」。切到这里时页面上的资产数字'
     '仍是全库数字（本期不按实例过滤），这一点在接口的 scope_note 里写明。')
ON CONFLICT (instance_id) DO NOTHING;

UPDATE domain
   SET note = '报表领域。已有实例「华电集团」，但该实例下还没有任何资产。'
 WHERE domain_id = 'report'
   AND note = '占位领域：结构上支持，目前没有实例也没有资产。';
