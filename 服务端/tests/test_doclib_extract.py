"""制度抽取：条款切分、特征识别的两个方向、数值幻觉核对。

这组测试盯的是纪律第 9 条——**误报和漏报同样致命**。
本功能的全部价值是那个数字：「制度里还有 N 条带阈值的条款没变成规则」。
  漏报 → 真该补的规则没被指出来；
  误报 → 「第二条 名词解释」被标成阈值条款，N 虚高，人去逐条看完发现全是废话，
         下次就不看了。两种都让这个数字失去意义。

数值核对那组盯的是另一件事：模型编阈值。
抽规则时编一个数字出来比不抽更糟——它以「有制度依据」的面目进规则清单，
而审定的人未必逐字回查原文。
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app import doclib_extract as dx  # noqa: E402


# ─────────────────────────────────────────────────────────────────────────────
# 条款切分
# ─────────────────────────────────────────────────────────────────────────────
def test_切条款带标题与位置():
    body = ("第一条 为规范差旅费管理，根据有关规定制定本办法。\n"
            "第二条（住宿费标准）处级人员住宿费每人每天不得超过460元。\n"
            "第三条 本办法自发布之日起施行。")
    cs = dx.split_clauses(body)
    assert [c["clause_no"] for c in cs] == ["第一条", "第二条", "第三条"]
    assert cs[1]["title"] == "住宿费标准"
    assert "460" in cs[1]["body"]
    assert cs[0]["pos"] < cs[1]["pos"] < cs[2]["pos"]


def test_切不出来就返回空不硬凑():
    """硬凑的后果：整份文件当成一条丢给模型，模型在几千字里挑一条编出来，
    而没人能对上是哪一条。"""
    assert dx.split_clauses("这是一份没有条款头的说明文字，讲了很多事情。") == []
    assert dx.split_clauses("") == []
    assert dx.split_clauses(None) == []


def test_太短的条款不计入():
    cs = dx.split_clauses("第一条 略。第二条 处级人员住宿费每人每天不得超过460元。")
    assert [c["clause_no"] for c in cs] == ["第二条"]


# ─────────────────────────────────────────────────────────────────────────────
# 特征识别 · 该命中的必须命中
# ─────────────────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("text,feature", [
    ("住宿费每人每天不得超过460元", "阈值"),
    ("住宿费标准为每人每天460元", "阈值"),
    ("出差时间在30天以上的，按长期出差处理", "阈值"),
    ("报销金额500元以下的免附明细", "阈值"),
    ("市内交通费每人每天80元", "数值"),
    ("不得使用公务卡以外的方式支付", "禁止"),
    ("严禁虚列差旅费", "禁止"),
    ("报销时应当附行程单", "强制"),
    ("须经分管领导批准", "强制"),
    ("确因工作需要超标准住宿的，经分管领导批准后可据实报销", "例外"),
    ("只能选择目录内的酒店", "名单制"),
])
def test_该命中的特征必须命中(text, feature):
    assert feature in dx.features_of(text), \
        "%r 没识别出「%s」：%s" % (text, feature, dx.features_of(text))


# ─────────────────────────────────────────────────────────────────────────────
# 特征识别 · 不该命中的一条都不许误伤
# ─────────────────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("text", [
    "本办法分为以下两类情形",
    "差旅费包括以下费用：城市间交通费、住宿费、伙食补助费",
    "以下统称差旅费",
    "本办法所称差旅费，是指工作人员临时到常住地以外地区公务出差所发生的费用",
    "第三章 报销流程",
])
def test_叙述性文字不许被标成阈值(text):
    """「以上/以下/以内」必须紧跟数字才算阈值。
    单独匹配这三个词，名词解释条会被标成阈值条款，候选数整体失真。"""
    assert "阈值" not in dx.features_of(text), \
        "%r 被误标成阈值条款：%s" % (text, dx.features_of(text))


def test_纯叙述条款不进候选():
    """候选门槛：光有「数值」不够（页码、序号都是数字），
    必须带阈值/禁止/强制/例外/名单制之一。"""
    feats = dx.features_of("本办法共分为五章二十八条")
    assert not (set(feats) & dx.CANDIDATE_FEATURES), feats


