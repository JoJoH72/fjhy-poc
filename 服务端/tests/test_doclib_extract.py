# ─────────────────────────────────────────────────────────────────────────────
# 数值核对：模型编的数字必须被揪出来
# ─────────────────────────────────────────────────────────────────────────────
def test_草稿里凭空多出的数字判为存疑():
    source = "处级人员住宿费每人每天不得超过460元。"
    draft = {"规则名称": "住宿费超标", "判定逻辑": "住宿费单价 > 460元 且 超过 3 天",
             "例外情形": None}
    chk = dx.check_numbers(draft, source)
    assert chk["ok"] is False
    vals = [s["value"].strip() for s in chk["suspect"]]
    assert any("3" in v for v in vals), chk
    assert not any("460" in v for v in vals), "原文里有的 460 被误判成幻觉：%s" % chk


def test_原文里有的数字不许误判():
    """误报一样要命：把对的草稿打上幻觉红标，人就不再信这个标。"""
    source = "市内交通费每人每天80元；往返中转站的，按40元报销。"
    draft = {"判定逻辑": "市内交通费 > 80元 判超标", "例外情形": "往返中转站按40元"}
    chk = dx.check_numbers(draft, source)
    assert chk["ok"] is True, chk


def test_千分位和空格不影响比对():
    source = "单次报销金额不得超过10000元。"
    draft = {"判定逻辑": "金额 > 10,000 元"}
    assert dx.check_numbers(draft, source)["ok"] is True


