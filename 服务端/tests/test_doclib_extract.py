def test_层级编号体():
    """差旅费共享审核要点用的是 1.3.9.1，不是「第X条」。
    只有条款体正则时，这份 PDF 切出 0 条——而它是审核口径最密的一份。"""
    t = ("1.3.9.1. 海运集团：需附《事权审批单》，船舶事项为3000元以上。\n"
         "1.3.9.2. 福港下属单位单笔200万元以上大额资金支付需要本部审批。\n"
         "1.3.9.3. 涉密项目审核需在意见区备注说明。")
    cs = dx.split_numbered(t)
    assert [c["clause_no"] for c in cs] == ["1.3.9.1", "1.3.9.2", "1.3.9.3"], cs
    assert "3000" in cs[0]["body"]


def test_表格行体():
    """差旅费审核规则.xlsx 每行就是一条规则——现有 82 条规则的
    source_clause.file 写的「规则表」指的就是它。用条款体正则切它得 0 条。"""
    t = ("# 差旅费\n"
         "序号 | 校验类型 | 校验规则 | 实现途径 | 校验方式 | 是否已有\n"
         "1 | 付款主体校验 | 付款主体需与核算主体完全一致 | 系统规则 | 警告 | 是\n"
         "2 | 住宿费标准控制 | 住宿费超标准的不允许提单 | 系统规则 | 禁止 | 是")
    cs = dx.split_table_rows(t)
    assert len(cs) == 2, cs
    assert cs[0]["clause_no"] == "第1行"
    assert cs[0]["title"] == "付款主体校验"
    # 不丢列：实现途径/校验方式是规则八要素里的现成字段
    assert "系统规则" in cs[0]["body"] and "警告" in cs[0]["body"]


def test_表头行不许收进来():
    """表头没有规则内容，收进来会变成一条「序号|校验类型|…」的假规则，
    而它会被算进「还有多少条没变成规则」的分母里。"""
    t = ("序号 | 校验类型 | 校验规则 | 实现途径\n"
         "1 | 付款主体校验 | 付款主体需与核算主体完全一致 | 系统规则")
    cs = dx.split_table_rows(t)
    assert len(cs) == 1 and cs[0]["clause_no"] == "第1行", cs


