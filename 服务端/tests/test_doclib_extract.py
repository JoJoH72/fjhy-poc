# ─────────────────────────────────────────────────────────────────────────────
# 候选口径：只排除范本，不是只收「制度」
# ─────────────────────────────────────────────────────────────────────────────
def test_名字不规整的制度文件也要能进候选():
    """实扫逼出来的：《差旅费解答六（国资委未转发）》第十三条带阈值+禁止+例外，
    是标准的待规则化条款。第一版候选门槛定成「只有文件名像制度的才算」，
    这一条就被判成「其他」类、一条候选都不进——漏报，而且是最该看的那一条。"""
    assert dx.kind_of("2.1差旅费解答六（国资委未转发）.pdf") == "制度"
    assert dx.kind_of("差旅费审核规则.xlsx") == "制度"
    assert "其他" in dx.CANDIDATE_KINDS, "名字认不出来的文件不许被排除在候选之外"
    assert "范本" not in dx.CANDIDATE_KINDS, "文书范本里的「第X条」会把候选数字污染掉"


def test_范本始终排除在候选之外():
    """合同、申请书里也有「第X条」，但那是文书条款不是制度条款。"""
    for n in ("借款合同.docx", "出差申请书.docx", "特别约定.docx"):
        assert dx.kind_of(n) == "范本", n


