# -*- coding: utf-8 -*-
"""演示单附件的合成示意图。

**为什么要有这个文件**：演示单的附件原本只有类型和文件名，`stored_path` 留空，
点开是 404、页面显示「无原图」。于是「真实数据和模拟数据都没有附件」成了
使用者的第一印象——而真实单的 219 张图一直是好的。给演示附件配一张
**一眼就知道是假的**图，演示时附件查看这条链路才是完整的。

**三条纪律**：
  1) **绝不拿真实客户的图去填演示单。** 那 219 张是客户的真实发票和出差申请单，
     含姓名、金额、车次。混进演示数据之后再也分不开，等于把客户 PII 散进演示环境。
     这里的图是现画的，不含任何真实业务信息。
  2) **一眼可辨**（全局纪律第 12 条）：满幅水印「演示数据」+ 顶部红条
     「演示数据 · 非真实凭证」+ 文件名前缀「【演示】」+ 单独的 demo/ 目录。
     不能让人在演示现场把它当成识别结果看。
  3) **容器里没有中文字体也不许崩、也不许静默画成豆腐块。** Dockerfile.backend
     现在装了 fonts-wqy-zenhei（就是候选表里的 wqy-zenhei.ttc），服务器上因此
     不走降级；但别的环境未必有，找不到中文字体时降级成英文文案并在返回值里
     把 `font` 标成 None，调用方可据此知道这批图是降级版。
"""
import os

# 中文字体候选。Windows 本机用前三个；Linux 容器里基本都没有，
# 列出来是「装了就能用」，不是「假定有」。
_FONT_CANDIDATES = (
    "C:/Windows/Fonts/msyh.ttc",            # 微软雅黑
    "C:/Windows/Fonts/simhei.ttf",          # 黑体
    "C:/Windows/Fonts/simsun.ttc",          # 宋体
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",
    "/usr/share/fonts/truetype/arphic/uming.ttc",
)

W, H = 760, 1040
_INK = (34, 34, 34)
_MUTED = (120, 120, 120)
_RED = (198, 40, 40)
_WM = (198, 40, 40, 26)          # 水印：很浅，不挡正文


def _font_path():
    for p in _FONT_CANDIDATES:
        if os.path.isfile(p):
            return p
    return None


def _load(path, size):
    from PIL import ImageFont
    if path:
        try:
            return ImageFont.truetype(path, size)
        except Exception:
            pass
    try:
        return ImageFont.load_default(size)
    except TypeError:          # Pillow < 10 的 load_default 不吃 size
        return ImageFont.load_default()


def render(out_path, bill_no, attach_type, seq, type_code=None):
    """画一张合成示意图，返回 {path, content_type, byte_size, font, degraded}。

    `out_path` 的父目录会被建出来。同名文件直接覆盖——这个函数是幂等的，
    重跑一遍得到的是同样的图（不含时间戳，避免每次 seed 都产生「新」文件）。
    """
    from PIL import Image, ImageDraw

    fp = _font_path()
    degraded = fp is None        # 没有中文字体 → 降级成英文文案
    f_title = _load(fp, 30)
    f_label = _load(fp, 19)
    f_body = _load(fp, 22)
    f_small = _load(fp, 15)
    f_wm = _load(fp, 64)

    img = Image.new("RGB", (W, H), (252, 252, 250))
    d = ImageDraw.Draw(img)

    # 顶部红条：最显眼的位置写最要紧的话
    d.rectangle([0, 0, W, 58], fill=_RED)
    d.text((24, 15), "演示数据 · 非真实凭证" if not degraded
           else "DEMO DATA - NOT A REAL VOUCHER",
           font=f_title if not degraded else f_body, fill=(255, 255, 255))

    # 页面边框
    d.rectangle([18, 76, W - 18, H - 18], outline=(214, 214, 210), width=2)

    rows = [
        ("附件类型" if not degraded else "Type", attach_type or "—"),
        ("单据号" if not degraded else "Bill No", bill_no),
        ("序号" if not degraded else "Seq", str(seq)),
    ]
    if type_code:
        rows.append(("细类编码" if not degraded else "Code", type_code))

    y = 120
    for label, value in rows:
        d.text((48, y), label, font=f_label, fill=_MUTED)
        d.text((188, y - 2), value, font=f_body, fill=_INK)
        y += 52

    d.line([48, y + 10, W - 48, y + 10], fill=(228, 228, 224), width=1)

    note = ([
        "这张图是演示用的合成示意图，由",
        "app/demo/demo_attachment_image.py 现画，",
        "不含任何真实业务信息。",
        "",
        "真实单的附件是从客户 xlsx 的内嵌图片",
        "抽出来的真图（source_kind=xlsx内嵌），",
        "两者在库里用 source_kind 区分，不会混。",
        "",
        "不要拿这张图验证识别或 OCR 效果。",
    ] if not degraded else [
        "Synthetic placeholder for demo bills.",
        "Generated by app/demo/demo_attachment_image.py.",
        "Contains no real business data.",
        "",
        "No CJK font found on this machine, so this",
        "image fell back to English text.",
    ])
    y += 40
    for line in note:
        d.text((48, y), line, font=f_small, fill=_MUTED)
        y += 26

    # 满幅斜水印。画在单独的 RGBA 图层上旋转后合成——
    # 直接在底图上转文字会把整张图转歪。
    layer = Image.new("RGBA", (W * 2, H * 2), (0, 0, 0, 0))
    ld = ImageDraw.Draw(layer)
    text = "演示数据" if not degraded else "DEMO"
    for gy in range(0, H * 2, 210):
        for gx in range(0, W * 2, 340):
            ld.text((gx, gy), text, font=f_wm, fill=_WM)
    layer = layer.rotate(30, expand=False)
    layer = layer.crop((W // 2, H // 2, W // 2 + W, H // 2 + H))
    img = Image.alpha_composite(img.convert("RGBA"), layer).convert("RGB")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    img.save(out_path, format="PNG", optimize=True)
    return {"path": out_path, "content_type": "image/png",
            "byte_size": os.path.getsize(out_path),
            "font": fp, "degraded": degraded}
